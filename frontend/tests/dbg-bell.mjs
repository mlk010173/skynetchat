import { chromium } from "playwright";
const code = process.env.CODE;
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
const errs = [];
p.on("pageerror", (e) => errs.push("PAGEERROR: " + e.message.slice(0, 200)));
p.on("console", (m) => m.type() === "error" && errs.push("CONSOLE: " + m.text().slice(0, 200)));
await p.goto("https://mlk010173.github.io/skynetchat/#/login", { waitUntil: "networkidle" });
await p.waitForTimeout(2500);
await p.fill('input[aria-label="Código de acesso"]', process.env.CODE);
await p.click("button:has-text('ENTRAR')");
await p.waitForTimeout(4500);
console.log("URL:", p.url());
await p.waitForTimeout(2000);
const badge = await p.locator(".bell-badge").textContent().catch(() => "(sem badge)");
console.log("badge:", badge);
await p.click('button[aria-label="Notificações"]');
await p.waitForTimeout(2000);
const panel = await p.textContent(".notif-panel").catch(() => "(PAINEL NÃO ABRIU)");
console.log("painel:", panel.slice(0, 200));
console.log("erros:", errs.slice(0, 4));
await b.close();
